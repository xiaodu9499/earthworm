function sentenceForFocus(focusIndex, item) {
  const verb = item.third ? item.action.third : item.action.base;
  const auxiliary = item.third ? "Does" : "Do";
  const perfect = item.third ? "has" : "have";
  const pastBe = item.be === "are" ? "were" : "was";
  const passiveBe = pluralPassiveObjects.has(item.objectEn) ? "were" : "was";
  const itemStartsWithArticle = /^(a|an|the|some)\s/i.test(item.itemEn);
  const quantityItem = itemStartsWithArticle ? item.itemEn : `a ${item.itemEn}`;

  switch (focusIndex) {
    case 0:
      return [
        `${item.actorEn} ${item.be} ${item.adjectiveEn}.`,
        `${item.actorZh}很${stateInChinese(item)}。`,
      ];
    case 1:
      return [`${item.actorEn} ${item.have} ${item.itemEn}.`, `${item.actorZh}有${item.itemZh}。`];
    case 2:
      return [
        `${item.actorEn} ${verb} ${item.objectEn} ${item.routineEn}.`,
        routineSentenceInChinese(item),
      ];
    case 3:
      return [
        `${item.actorEn} ${item.be} ${item.action.ing} ${item.objectEn} ${item.placeEn}.`,
        `${item.actorZh}${item.placeZh}正在${item.action.zh}${item.objectZh}。`,
      ];
    case 4:
      return [
        `${item.actorEn} ${item.action.past} ${item.objectEn} ${item.pastTimeEn}.`,
        `${item.actorZh}${item.pastTimeZh}${item.action.zh}了${item.objectZh}。`,
      ];
    case 5:
      return [
        `${item.actorEn} will ${item.action.base} ${item.objectEn} ${item.futureTimeEn}.`,
        `${item.actorZh}${item.futureTimeZh}会${item.action.zh}${item.objectZh}。`,
      ];
    case 6:
      return [
        `${auxiliary} ${midSentenceActor(item.actorEn)} ${item.action.base} ${item.objectEn} ${item.routineEn}?`,
        questionSentenceInChinese(item),
      ];
    case 7:
      return [
        `${item.actorEn} should ${item.action.base} ${item.objectEn} ${item.placeEn}.`,
        `${item.actorZh}应该${item.placeZh}${item.action.zh}${item.objectZh}。`,
      ];
    case 8:
      return [
        `${item.actorEn} ${item.be} ${item.comparativeEn} than ${comparisonTarget(item)[0]}.`,
        `${item.actorZh}比${comparisonTarget(item)[1]}${item.comparativeZh}。`,
      ];
    case 9:
      return [`There is ${quantityItem} ${item.placeEn}.`, `${item.placeZh}有${item.itemZh}。`];
    case 10:
      return [
        `${item.actorEn} ${perfect} ${item.action.participle} ${item.objectEn} before.`,
        `${item.actorZh}以前${item.action.zh}过${item.objectZh}。`,
      ];
    case 11:
      return [
        `If ${midSentenceActor(item.actorEn)} ${verb} ${item.objectEn}, ${item.pronounEn} will be ${item.adjectiveEn}.`,
        `如果${item.actorZh}${item.action.zh}${item.objectZh}，${item.pronounZh}会很${stateInChinese(item)}。`,
      ];
    case 12:
      return [
        `${capitalize(item.objectEn)} ${passiveBe} ${item.action.participle} by ${item.byEn} ${item.pastTimeEn}.`,
        `${item.pastTimeZh}，${item.objectZh}由${item.actorZh}${item.action.zh}。`,
      ];
    case 13:
      return [
        `The ${item.personEn} who ${item.action.third} ${item.objectEn} is ${item.adjectiveEn}.`,
        `${item.action.zh}${item.objectZh}的${item.personZh}很${stateInChinese(item)}。`,
      ];
    case 14:
      return [
        `Although ${midSentenceActor(item.actorEn)} ${pastBe} ${item.adjectiveEn}, ${item.pronounEn} ${item.action.past} ${item.objectEn}.`,
        `虽然${item.actorZh}很${stateInChinese(item)}，但${item.pronounZh}还是${item.action.zh}了${item.objectZh}。`,
      ];
    default:
      throw new Error(`Unknown focus index: ${focusIndex}`);
  }
}

