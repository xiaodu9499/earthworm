function buildCourse(stage, focusIndex, order) {
  const [focusTitle, focusDescription] = focusDefinitions[focusIndex];
  const id = `${stage.id}-lesson-${String(order).padStart(2, "0")}`;
  return {
    id,
    title: `${stage.stageLabel} ${String(order).padStart(2, "0")} · ${focusTitle}`,
    description: focusDescription,
    video: "",
    order,
    coursePackId: stage.id,
    statements: stage.scenarios.map((item, statementIndex) => {
      const [english, chinese] = sentenceForFocus(focusIndex, item);
      return {
        id: `${id}-statement-${String(statementIndex + 1).padStart(2, "0")}`,
        order: statementIndex + 1,
        chinese,
        english,
      };
    }),
  };
}

function buildPack(stage, stageIndex) {
  const generatedCourses = focusDefinitions.map((_, focusIndex) =>
    buildCourse(stage, focusIndex, focusIndex + 1),
  );
  const courses =
    stageIndex === 0
      ? [...preservedFoundationCourses, ...generatedCourses.slice(5)]
      : generatedCourses;

  return {
    id: stage.id,
    order: stage.order,
    title: stage.title,
    description: stage.description,
    isFree: true,
    cover: "/logo.png",
    creatorId: "local-user",
    shareLevel: "public",
    source: {
      structureOnly: true,
      content:
        "All Chinese and English practice statements are original Earthworm curriculum content. No textbook passages, answer keys, PDF or DOCX content, transcripts, or publisher audio are included.",
    },
    courses,
  };
}

