function validateCatalog(nextCatalog) {
  const ids = new Set();
  const englishSentences = new Set();

  if (nextCatalog.packs.length !== 4) throw new Error("Expected four original course stages.");

  nextCatalog.packs.forEach((pack, packIndex) => {
    if (pack.order !== packIndex + 10) throw new Error(`Unexpected pack order: ${pack.id}`);
    if (pack.courses.length !== 15) throw new Error(`Expected 15 courses in ${pack.id}.`);
    registerId(pack.id);

    pack.courses.forEach((course, courseIndex) => {
      if (course.order !== courseIndex + 1)
        throw new Error(`Unexpected course order: ${course.id}`);
      if (course.coursePackId !== pack.id) throw new Error(`Wrong course pack id: ${course.id}`);
      if (course.statements.length !== 12)
        throw new Error(`Expected 12 statements in ${course.id}.`);
      registerId(course.id);

      course.statements.forEach((statement, statementIndex) => {
        if (statement.order !== statementIndex + 1) {
          throw new Error(`Unexpected statement order: ${statement.id}`);
        }
        if (!statement.chinese.trim() || !statement.english.trim()) {
          throw new Error(`Empty statement content: ${statement.id}`);
        }
        registerId(statement.id);
        const normalizedEnglish = statement.english.toLocaleLowerCase("en-US");
        if (englishSentences.has(normalizedEnglish)) {
          throw new Error(`Duplicate English statement: ${statement.english}`);
        }
        englishSentences.add(normalizedEnglish);
      });
    });
  });

  function registerId(id) {
    if (ids.has(id)) throw new Error(`Duplicate id: ${id}`);
    ids.add(id);
  }
}
